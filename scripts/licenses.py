#!/usr/bin/env python3
"""
Inventory the licenses of everything freeharness ships or installs, and write
THIRD_PARTY_LICENSES.md. Fails (exit 1) on a license that is not on the permissive allow-list,
so a new dependency cannot slip a copyleft/unknown license in unreviewed.

    python scripts/licenses.py            # rewrite THIRD_PARTY_LICENSES.md, exit 1 if review needed
Needs the harness installed (`freeharness setup`) to inventory the npm side.
"""
from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Reviewed by hand: acceptable, with the reason. Anything else non-permissive fails the script.
REVIEWED = {
    "@deepseek-ai/libreoffice-kit": "MPL-2.0: file-level copyleft; installed unmodified from npm by the user, not redistributed by this project",
    "@deepseek-ai/libreoffice-kit-wasm": "MPL-2.0: as above",
    "@img/sharp-libvips-linux-x64": "LGPL-3.0: dynamically loaded native library, unmodified, installed from npm by the user",
}
ALLOWED = ("MIT", "ISC", "BSD", "APACHE", "PSF", "0BSD", "UNLICENSE", "CC0", "BLUEOAK", "PYTHON-2.0")


def py_deps(root="freeharness"):
    seen, todo = {}, [root]
    while todo:
        name = todo.pop()
        key = re.split(r"[<>=!~; \[(]", name.strip(), maxsplit=1)[0].lower().replace("_", "-")
        if key in seen:
            continue
        try:
            d = metadata.distribution(key)
        except metadata.PackageNotFoundError:
            continue
        lic = d.metadata.get("License-Expression") or ""
        if not lic:
            cls = [c.split("::")[-1].strip() for c in (d.metadata.get_all("Classifier") or []) if c.startswith("License ::")]
            raw = d.metadata.get("License") or ""
            lic = "; ".join(cls) or (raw if raw and len(raw) <= 60 and "\n" not in raw else "UNKNOWN")
        seen[key] = (d.version, lic)
        for req in d.requires or []:
            if "extra ==" not in req:
                todo.append(req)
    seen.pop(root, None)
    return seen


def npm_deps(node_modules: Path):
    out = {}
    for pj in node_modules.glob("**/package.json"):
        if "/templates/" in pj.as_posix():       # documentation templates inside a skill, never run
            continue
        try:
            d = json.loads(pj.read_text())
        except (OSError, ValueError):
            continue
        name, ver = d.get("name"), d.get("version")
        if not name or not ver:
            continue
        lic = d.get("license") or ("; ".join(x.get("type", "?") for x in d.get("licenses", [])) if d.get("licenses") else "UNKNOWN")
        if isinstance(lic, dict):
            lic = lic.get("type", "UNKNOWN")
        out[f"{name}@{ver}"] = str(lic)
    return out


def ok(lic: str) -> bool:
    parts = re.split(r"[ ()/;,]+|\bOR\b|\bAND\b", lic.upper())
    return any(any(a in p for a in ALLOWED) for p in parts if p)


def main() -> int:
    from freeharness import paths
    py = py_deps()
    nm = paths.harness_dir() / "node_modules"
    npm = npm_deps(nm) if nm.is_dir() else {}
    bad = {k: v for k, v in {**{f"{k}=={a}": b for k, (a, b) in py.items()}, **npm}.items()
           if not ok(v) and k.rsplit("@", 1)[0] not in REVIEWED}
    from collections import Counter
    counts = Counter(npm.values())
    lines = ["# Third-party licenses", "",
             "Generated by `scripts/licenses.py`. freeharness itself is MIT (see LICENSE).", "",
             "## Bundled code", "",
             "- **DeepSeek Harness** (`@deepseek-ai/dsh` 0.2.1-rc.2), MIT, Copyright (c) 2026 DeepSeek. "
             "Installed from npm by `freeharness setup`, not copied into this repository; its license text is kept in "
             "`harness/DSH-LICENSE` and ships inside the npm package.", "",
             "## Python runtime dependencies", "", "| package | version | license |", "|---|---|---|"]
    lines += [f"| {k} | {a} | {b} |" for k, (a, b) in sorted(py.items())]
    lines += ["", f"## npm dependencies of the harness ({len(npm)} packages)", "", "| license | packages |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in counts.most_common()]
    lines += ["", "## Reviewed exceptions (copyleft-family licenses)", ""]
    lines += [f"- `{k}`: {v}" for k, v in REVIEWED.items()]
    lines += ["", "## Needs review" if bad else "## Needs review: none", ""]
    lines += [f"- {k}: {v}" for k, v in sorted(bad.items())]
    (ROOT / "THIRD_PARTY_LICENSES.md").write_text("\n".join(lines) + "\n")
    print(f"python deps: {len(py)}, npm deps: {len(npm)}, needing review: {len(bad)}")
    for k, v in sorted(bad.items()):
        print("  review:", k, v)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
