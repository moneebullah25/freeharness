"""
Answering dsh's approval requests (sandbox escalation) from the terminal client.

dsh's JSON-RPC `sdk` profile never sends the client a request (sdk-protocol README:
"server -> client requests are a dead capability"), so approval cannot travel over it.
Instead the fh-guard plugin inside dsh (data/fh_guard.mjs) connects to a unix socket this
module serves, sends {sessionId, toolName, callId, reason}, and gets one of
`allowed-once | rejected | cancelled` back. Everything else (no socket, closed, error,
timeout) is "unavailable" on the dsh side: the action stays denied.

Rules: only a human (or, in tests, an explicit scripted decision object) answers. The model's
text is never consulted. There is no "approve everything" mode, and `-p` runs without an
approver at all (dsh policy `never`: refused at once, the model is told not to ask).
"""
from __future__ import annotations

import json
import os
import re
import secrets
import shutil
import socket
import sys
import tempfile
import threading
import time
from pathlib import Path

APPROVAL_PATCH = """\
# generated by freeharness: an answerer exists for this runtime, so ask instead of `never`
- id: approval
  config:
    policy: ask
- id: permission
  config:
    presets:
      read-only:
        sandbox: read-only
        approval: ask
      workspace-write:
        sandbox: workspace-write
        approval: ask
    defaultPreset: workspace-write
"""

_MODE = re.compile(r"escalate sandbox to ([a-z-]+): (.*)", re.S)


def parse_reason(reason: str) -> tuple[str, str]:
    """('danger-full-access', 'justification') from dsh's reason text; ('', reason) if it is another kind."""
    m = _MODE.match(reason or "")
    return (m.group(1), m.group(2)) if m else ("", reason or "")


class Approver:
    """Serves the approval socket. Subclasses override `decide`."""

    def __init__(self):
        self._dir: Path | None = None
        self._srv: socket.socket | None = None
        self._stop = threading.Event()
        self._calls: dict[str, tuple[str, dict]] = {}
        self._cond = threading.Condition()
        self.token = secrets.token_hex(16)
        self.log: list[dict] = []                 # every request and outcome, for tests and audits

    # -- what dsh needs ----------------------------------------------------

    def start(self):
        self._dir = Path(tempfile.mkdtemp(prefix="fh-appr-"))
        self._dir.chmod(0o700)
        self.sock_path = self._dir / "s"
        self._srv = socket.socket(socket.AF_UNIX)
        self._srv.bind(str(self.sock_path))
        os.chmod(self.sock_path, 0o600)
        self._srv.listen(8)
        self._srv.settimeout(0.3)
        self._stop.clear()
        threading.Thread(target=self._serve, daemon=True).start()
        (self._dir / "approval.patch.yml").write_text(APPROVAL_PATCH)

    @property
    def patch(self) -> Path:
        return self._dir / "approval.patch.yml"

    def env(self) -> dict[str, str]:
        return {"FH_APPROVAL_SOCK": str(self.sock_path), "FH_APPROVAL_TOKEN": self.token}

    def close(self):
        self._stop.set()
        if self._srv:
            try:
                self._srv.close()
            except OSError:
                pass
        if self._dir:
            shutil.rmtree(self._dir, ignore_errors=True)
        self._srv = self._dir = None

    # -- tool calls seen on the session stream (the request itself carries no arguments) ----

    def observe(self, event: dict):
        if event.get("type") != "tool/call":
            return
        d = event.get("data") or {}
        args = d.get("arguments")
        try:
            args = json.loads(args) if isinstance(args, str) else (args or {})
        except json.JSONDecodeError:
            args = {"_raw": str(args)}
        with self._cond:
            self._calls[str(d.get("callId") or d.get("id") or "")] = (d.get("name") or "?", args)
            self._cond.notify_all()

    def _call_for(self, call_id, wait=1.5):
        deadline = time.monotonic() + wait
        with self._cond:
            while call_id not in self._calls and time.monotonic() < deadline:
                self._cond.wait(0.1)
            return self._calls.get(str(call_id))

    # -- socket ------------------------------------------------------------

    def _serve(self):
        while not self._stop.is_set():
            try:
                conn, _ = self._srv.accept()
            except socket.timeout:
                continue
            except OSError:
                return
            threading.Thread(target=self._handle, args=(conn,), daemon=True).start()

    def _handle(self, conn: socket.socket):
        outcome = "unavailable"
        req = {}
        try:
            buf = b""
            conn.settimeout(5)
            while b"\n" not in buf:
                chunk = conn.recv(65536)
                if not chunk:
                    return
                buf += chunk
            req = json.loads(buf.split(b"\n", 1)[0])
            if not secrets.compare_digest(str(req.get("token", "")), self.token):
                req = {}                                   # not our plugin: refuse, and do not log it as a request
                return
            mode, why = parse_reason(req.get("reason", ""))
            call = self._call_for(req.get("callId"))
            conn.settimeout(None)
            outcome = self.decide({"sessionId": req.get("sessionId"), "toolName": req.get("toolName"),
                                   "callId": req.get("callId"), "mode": mode, "justification": why,
                                   "reason": req.get("reason", ""), "call": call})
            if outcome not in ("allowed-once", "rejected", "cancelled"):
                outcome = "rejected"
        except Exception:                                  # noqa: BLE001  any failure is a denial
            outcome = "rejected" if req else "unavailable"
        finally:
            if req:
                self.log.append({"request": req, "outcome": outcome})
            try:
                conn.sendall((json.dumps({"outcome": outcome}) + "\n").encode())
            except OSError:
                pass
            conn.close()

    def decide(self, request: dict) -> str:               # pragma: no cover - overridden
        return "rejected"


class DenyAll(Approver):
    """Answers every request 'rejected' (a runtime with an answerer wired but nobody to ask)."""


class FixedAnswer(Approver):
    """For tests: a scripted human. Never use outside tests; there is no such CLI flag."""

    def __init__(self, outcome: str):
        super().__init__()
        self.outcome = outcome

    def decide(self, request):
        return self.outcome


class TerminalApprover(Approver):
    """Asks the person at the terminal: shows the command and the mode requested, default NO."""

    def __init__(self, console, status=None, stdin=None):
        super().__init__()
        self.c, self.status = console, status
        self.stdin = stdin if stdin is not None else sys.stdin
        self._prompt_lock = threading.Lock()

    def decide(self, request):
        if not self.stdin.isatty():
            return "rejected"                              # nobody to ask: deny, do not wait
        call = request.get("call")
        with self._prompt_lock:
            st = self.status
            if st:
                st.stop()
            try:
                self.c.print()
                self.c.print("[bold yellow]approval needed[/]")
                if call:
                    name, args = call
                    shown = args.get("command") or args.get("file_path") or json.dumps(args)[:300]
                    self.c.print(f"  tool      {name}")
                    self.c.print(f"  command   {str(shown)[:400]}", markup=False)
                self.c.print(f"  asks for  [bold]{request['mode'] or 'a wider permission'}[/]"
                             + ("  [red](no sandbox at all)[/]" if request["mode"] == "danger-full-access" else ""))
                if request["justification"]:
                    self.c.print(f"  model says: {request['justification'][:300]}", markup=False)
                try:
                    answer = input("allow this once? [y/N] ").strip().lower()
                except (EOFError, KeyboardInterrupt):
                    answer = ""
                return "allowed-once" if answer in ("y", "yes") else "rejected"
            finally:
                if st:
                    st.start()
